"""HAPPY VALLEY - generate the oval track maps and the ROM's path tables from tests/hv_geom.py.

    python games/happyvalley/design/gen_track.py

Writes res/maps/hv.map and st.map (gbe_world maps of greybox metatiles: turf/dirt track, rails,
infield, stands above the home straight, city around) and src/track_data.c/.h (per course a point every
hv_geom.STEP_M metres: x, y as u16 and the heading 0..63; the sine table). Re-run after changing the
geometry; the art pass replaces the metatiles, not this layout.
"""
import math
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(GAME.parents[1] / "harness"))
sys.path.insert(0, str(GAME / "tests"))
import hv_geom as G          # noqa: E402
import hv_model as M         # noqa: E402

W = G.LANES * G.LANE_PX      # track width (px)
LEGEND = {"GROUND": "_", "TURF": ".", "DIRT": ":", "RAIL": "#", "INFIELD": ",", "STAND": "S",
          "CITY": "C", "FINISH": "|"}


def offset(track, x, y):
    """Outward distance (px) from the track's inside rail (negative = infield)."""
    t = G.TRACKS[track]
    s, r = G._px(t["straight"]), G._px(t["radius"])
    fx, fy = G.finish(track)
    ax, ay = fx - s, fy + r
    nx = min(max(x, ax), fx)
    return math.hypot(x - nx, y - ay) - r


def cell(map_name, x, y):
    tracks = [k for k, t in G.TRACKS.items() if t["map"] == map_name]
    fx, fy = G.finish(map_name)
    d = offset(map_name, x, y)
    if 0 <= d <= W:
        if abs(x - fx) < 8 and y < fy + 8:
            return "FINISH"
        return "TURF"
    if -16 <= d < 0 or W < d <= W + 16:
        return "RAIL"
    for tr in tracks:
        if tr == map_name:
            continue
        da = offset(tr, x, y)
        if 0 <= da <= W:
            return "DIRT"
        if -16 <= da < 0 or W < da <= W + 16:
            return "RAIL"
    if d < 0:
        return "INFIELD"
    t = G.TRACKS[map_name]
    left = fx - G._px(t["straight"]) - G._px(t["radius"])
    if y < fy - W - 16 and left < x < fx + G._px(t["radius"]):
        return "STAND"
    return "CITY" if d > W + 48 else "GROUND"


def write_map(map_name):
    w, h = G.map_size_sectors(map_name)
    rows = []
    for cy in range(h * 16):
        rows.append("".join(LEGEND[cell(map_name, cx * 16 + 8, cy * 16 + 8)] for cx in range(w * 16)))
    lines = [f"; HAPPY VALLEY {map_name}: generated by design/gen_track.py from tests/hv_geom.py - do not edit",
             f"@ map {map_name}", "@ metatiles metatiles", f"@ size {w} {h}", "@ border CITY", "legend:"]
    lines += [f"{ch} {name}" for name, ch in LEGEND.items()]
    lines += ["grid:"] + rows
    (GAME / "res" / "maps" / f"{map_name.lower()}.map").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return w, h


def write_tables():
    c = ["// Generated by design/gen_track.py from tests/hv_geom.py - do not edit",
         "#pragma bank 255", "#include <gb/gb.h>", "#include <stdint.h>", '#include "track_data.h"', "",
         "BANKREF(track_data)"]
    refs = []
    for cid in M.COURSE_IDS:
        pts = G.table(cid)
        data = ", ".join(f"{x & 255}, {x >> 8}, {y & 255}, {y >> 8}, {hh}" for x, y, hh in pts)
        c.append(f"const uint8_t track_{cid.lower()}[] = {{ {data} }};")
        refs.append((cid, len(pts), G.TRACKS[G.track_of(cid)]["map"]))
    c.append("const track_ref_t track_index[] = {")
    c += [f"    {{ track_{cid.lower()}, {n}, MAP_{mp} }}," for cid, n, mp in refs]
    c.append("};")
    c.append("const int8_t sine64[64] = { " + ", ".join(str(v) for v in G.sine64()) + " };")
    (GAME / "src" / "track_data.c").write_text("\n".join(c) + "\n", encoding="utf-8")
    hdr = ["// Generated by design/gen_track.py - do not edit", "#pragma once", "#include <gb/gb.h>",
           "#include <stdint.h>", '#include "world_index.h"', "",
           f"#define TRACK_STEP_M {G.STEP_M}         // metres between path points",
           f"#define TRACK_LANE_PX {G.LANE_PX}", f"#define TRACK_MAX_POINTS {max(n for _, n, _ in refs)}",
           "typedef struct { const uint8_t *pts; uint16_t n; uint8_t map; } track_ref_t;   // pts: x16 y16 h",
           "extern const track_ref_t track_index[];", "extern const int8_t sine64[64];", "BANKREF_EXTERN(track_data)"]
    (GAME / "src" / "track_data.h").write_text("\n".join(hdr) + "\n", encoding="utf-8")


if __name__ == "__main__":
    for m in ("HV", "ST"):
        print(m, "sectors", write_map(m))
    write_tables()
    print("ok")
