# ================================================================== PAUSE (window full screen)
VISITED = {(1, 3), (1, 2), (0, 2), (2, 2), (1, 1), (0, 1), (2, 1), (1, 0)}
LINKS = (((1, 3), (1, 2)), ((1, 2), (0, 2)), ((1, 2), (2, 2)), ((1, 2), (1, 1)), ((1, 1), (0, 1)),
         ((1, 1), (2, 1)), ((1, 1), (1, 0)))


def pause(name, header, sample):
    s = Screen(name, header, text=HUD_TEXT, center=["MAPA"] + (["ANTESALA"] if sample else []))
    s.hud("♥♥♦" if sample else "♥♥♥")
    s.box(2, 0, 17, 19, tab="Mapa")
    if sample:
        for (c, r) in VISITED:
            x, y = 4 + 4 * c, 4 + 3 * r
            s.text(y, x, "<_>")
            s.text(y + 1, x, "(=)")
        for (a, b) in LINKS:
            (c0, r0), (c1, r1) = sorted((a, b))
            if r0 == r1:                      # horizontal link: gap col, both rows of the box
                x, y = 4 + 4 * c0 + 3, 4 + 3 * r0
                s.put(y, x, "┬")
                s.put(y + 1, x, "┴")
            else:                             # vertical link: gap row, middle col
                x, y = 4 + 4 * c0 + 1, 4 + 3 * r0 + 2
                s.put(y, x, "│")
        s.text(16, 6, "Antesala")             # name run: cols 6-13 (8 tiles), centred on the screen
    return s


