# Proportional text (game.json "vwf", text slot of 90 tiles, ui.md 1.3). Every text is drawn
# left-aligned in its cells unless listed in center:. A centred run is only centred on the
# screen/box when it has an even number of cells around column 10 (texts chosen for that).
# Play scene: the HUD numbers own slot tiles 0-2; the overlays (dialogue, item message, pause) are
# never shown together, so they share the range from 3. Boxes without a speaker tab start 10 tiles
# later so their lines get the same tiles as dialogo's (line 1 = 13-30, 2 = 31-48, 3 = 49-66).
HUD_TEXT = 3                                  # bombs 2 + keys 1 (hud_full)
TAB = 10                                      # "Don Terron"
LINE = 18                                     # one dialogue line: 18 cells = 144 px

