# ================================================================== DIALOGUE (window rows 2-6)
def dialog(name, header, lines, speaker=None, arrow=True, center=()):
    """Dynamic sample lines are exactly 18 chars, so each line run reserves the 18 tiles a full
    144 px line needs (proportional text fills ~70% of them: a real line holds ~25 chars)."""
    off = HUD_TEXT + (0 if speaker else TAB)
    s = Screen(name, header, text=off, center=(["DON_TERRON"] if speaker else []) + list(center))
    s.hud("♥♥♥")                              # hearts only: HUD digits would take overlay tiles
    s.box(2, 0, 6, 19, tab=speaker)
    for i, ln in enumerate(lines):
        assert len(ln) <= LINE, ln
        s.text(3 + i, 1, ln)
    if arrow:
        s.put(6, 17, "▼")
    return s


