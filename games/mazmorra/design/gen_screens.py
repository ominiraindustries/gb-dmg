"""Generate games/mazmorra/design/screens/*.screen except the title ones (paint_title.py).
Boxes come from helpers so rows are always 20 chars; texts use ' ' for blanks.

    python games/mazmorra/design/gen_screens.py && python harness/gb.py preview mazmorra

Window screens (HUD, dialogue, pause) are drawn in SCREEN coordinates with WY = 0, WX = 7, so a
screen row is also the window map row. The room under the window is the world engine's BG and is
left blank here (QA compares only the window rows with gb.mockup_errors(name, region)).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "games/mazmorra/design/screens"
sys.path.insert(0, str(ROOT / "harness"))
import asciitiles  # noqa: E402

ES = asciitiles.parse(ROOT / "harness/common/font_mini_es.tiles")[1]

LEGEND = {
    "<": "ui:FRAME_TL", "_": "ui:FRAME_T", ">": "ui:FRAME_TR", "{": "ui:FRAME_L", "}": "ui:FRAME_R",
    "(": "ui:FRAME_BL", "=": "ui:FRAME_B", ")": "ui:FRAME_BR", "▼": "ui:ARROW_DOWN", "*": "ui:CURSOR",
    "♥": "ui:HEART_FULL", "♦": "ui:HEART_HALF", "♡": "ui:HEART_EMPTY",
    "●": "ui:BOMB", "φ": "ui:KEY", "Ψ": "ui:BOSS_KEY", "█": "ui:SOLID",
    "│": "ui:MAP_DOOR_V", "┬": "ui:MAP_DOOR_H_T", "┴": "ui:MAP_DOOR_H_B",
    "?": "font_mini:QUESTION", "!": "font_mini:EXCLAM", ":": "font_mini:COLON", "-": "font_mini:DASH",
    "·": "font_mini:DOT",
}
for ch, lab in ((",", "COMMA"), ("'", "APOSTROPHE"), ("¡", "EXCL_OPEN"), ("¿", "QUEST_OPEN")):
    assert lab in ES
    LEGEND[ch] = f"font_mini_es:{lab}"


class Screen:
    def __init__(self, name, header, text=0, center=()):
        """text: first tile of this screen's proportional texts in the text slot (ui.md 1.3);
        center: text names (SCREEN_<NAME>_AT_<TEXT>) drawn centred in their cells."""
        self.name, self.header, self.offset, self.centre = name, header, text, list(center)
        self.g = [["."] * 20 for _ in range(18)]
        self.sprites = []

    def put(self, r, c, ch):
        assert 0 <= r < 18 and 0 <= c < 20, (self.name, r, c, ch)
        self.g[r][c] = ch

    def text(self, r, c, s):
        assert c + len(s) <= 20, (self.name, r, c, s)
        for i, ch in enumerate(s):
            self.put(r, c + i, "." if ch == " " else ("·" if ch == "." else ch))

    def center(self, r, s, c0=0, c1=19):
        """Centre s between columns c0..c1 (odd leftovers go right)."""
        self.text(r, c0 + (c1 - c0 + 1 - len(s)) // 2, s)

    def fill(self, r0, c0, r1, c1, ch):
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                self.put(r, c, ch)

    def box(self, r0, c0, r1, c1, tab=None):
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                top, bot, left, right = r == r0, r == r1, c == c0, c == c1
                ch = "."
                if top:
                    ch = "<" if left else (">" if right else "_")
                elif bot:
                    ch = "(" if left else (")" if right else "=")
                elif left:
                    ch = "{"
                elif right:
                    ch = "}"
                self.put(r, c, ch)
        if tab:                               # gbe_tbox tab: blank, name from col +3, blank
            self.text(r0, c0 + 2, " " + tab + " ")

    def hud(self, hearts="♥♥♥", bombs=None, keys=None, boss=False):
        """Window row 0 (row 1 stays BLANK: no separator line, user preference)."""
        self.text(0, 1, hearts)
        if bombs is not None:
            self.put(0, 11, "●")
            self.text(0, 12, str(bombs))          # left-aligned after the icon
        if keys is not None:
            self.put(0, 15, "φ")
            self.text(0, 16, str(keys))
        if boss:
            self.put(0, 18, "Ψ")

    def write(self):
        rows = ["".join(r) for r in self.g]
        used = sorted({ch for row in rows for ch in row if ch in LEGEND})
        lines = ["; " + h if h else ";" for h in self.header]
        lines += ["; Generated by design/gen_screens.py: edit there, not here.",
                  "tilesets: ui font_mini font_mini_lower font_mini_es"]
        if self.offset:
            lines.append(f"text: {self.offset}")
        if self.centre:
            lines.append("center: " + " ".join(self.centre))
        lines.append("legend:")
        lines += [f"{ch} {LEGEND[ch]}" for ch in used]
        lines.append("grid:")
        for row in rows:
            assert len(row) == 20, (self.name, row)
            lines.append(row)
        lines.append("sprites:")
        lines += self.sprites
        (OUT / f"{self.name}.screen").write_text("\n".join(lines) + "\n", encoding="utf-8")


